def _or_field(field: str, values: list[str]) -> str:
    return "(" + " OR ".join(f'"{v}"{field}' for v in values) + ")"


def _queries() -> list[dict]:
    jour = _or_field("[jour]", GI_JOURNALS)
    genj = _or_field("[jour]", GEN_JOURNALS)
    mesh = _or_field("[MeSH]", GI_MESH)
    mesh_major = _or_field("[MeSH Major Topic]", GI_MESH)
    guide = _or_field("[pt]", GUIDE_PUBTYPES)
    trial = _or_field("[pt]", TRIAL_PUBTYPES)
    title_guide = ("(" + " OR ".join(
        f'"{t}"[ti]' for t in ("guideline", "guidelines", "consensus",
                              "recommendations", "position statement",
                              "clinical practice update", "expert review")
    ) + ")")
    return [
        # Guidelines / consensus, GI-hepatology journals
        {"name": "guide_journal", "kind": "guideline",
         "max": MAX_GUIDE_CANDIDATES,
         "term": f"(({guide}) OR ({title_guide})) AND ({jour})"},
        # Guidelines / consensus on GI-hepatology topics, any indexed journal
        {"name": "guide_topic", "kind": "guideline",
         "max": MAX_GUIDE_CANDIDATES,
         "term": f"(({guide}) OR ({title_guide})) AND ({mesh})"},
        # Trials / meta-analyses / systematic reviews, GI-hepatology journals
        {"name": "trial_journal", "kind": "trial",
         "max": MAX_TRIAL_CANDIDATES,
         "term": f"({trial}) AND ({jour})"},
        # Major general journals carrying GI-hepatology major-topic trials
        {"name": "trial_general", "kind": "trial",
         "max": max(6, MAX_TRIAL_CANDIDATES // 2),
         "term": f"({trial}) AND ({genj}) AND ({mesh_major})"},
    ]


def _pubdate_str(node) -> str:
    """PubDate/ArticleDate element -> ISO date string (best effort)."""
    if node is None:
        return ""
    y = (node.findtext("Year") or "").strip()
    if not y:
        medline = (node.findtext("MedlineDate") or "").strip()
        m = re.search(r"(19|20)\d{2}", medline)
        return m.group(0) if m else ""
    mon = (node.findtext("Month") or "").strip()
    day = (node.findtext("Day") or "").strip()
    mm = "01"
    if mon:
        names = ("jan", "feb", "mar", "apr", "may", "jun", "jul", "aug",
                 "sep", "oct", "nov", "dec")
        low = mon.lower()[:3]
        mm = (f"{names.index(low) + 1:02d}" if low in names
              else (mon.zfill(2) if mon.isdigit() else "01"))
    return f"{y}-{mm}-{day.zfill(2) if day.isdigit() else '01'}"


def parse_pubmed_xml(xml_bytes: bytes) -> list[dict]:
    try:
        root = ET.fromstring(xml_bytes)
    except ET.ParseError as e:
        raise RuntimeError(f"PubMed XML parse error: {e}") from e
    items: list[dict] = []
    for pa in root.iter("PubmedArticle"):
        cit = pa.find("MedlineCitation")
        if cit is None:
            continue
        pmid = (cit.findtext("PMID") or "").strip()
        art = cit.find("Article")
        if art is None or not pmid:
            continue
        title = re.sub(r"\s+", " ", "".join(
            (art.find("ArticleTitle").itertext()
             if art.find("ArticleTitle") is not None else ""))).strip()
        journal = ""
        pubdate = epub = ""
        j = art.find("Journal")
        if j is not None:
            journal = (j.findtext("ISOAbbreviation")
                       or j.findtext("Title") or "").strip()
            ji = j.find("JournalIssue")
            if ji is not None:
                pubdate = _pubdate_str(ji.find("PubDate"))
        ad = art.find("ArticleDate")
        if ad is not None:
            epub = _pubdate_str(ad)
        parts = []
        for at in art.findall(".//Abstract/AbstractText"):
            label = (at.get("Label") or "").strip()
            txt = re.sub(r"\s+", " ", "".join(at.itertext())).strip()
            if not txt:
                continue
            parts.append(f"{label}: {txt}" if label else txt)
        abstract = " ".join(parts)
        doi = ""
        for el in art.findall("ELocationID"):
            if (el.get("EIdType") or "").lower() == "doi":
                doi = (el.text or "").strip()
        authors = []
        for a in art.findall(".//AuthorList/Author"):
            ln = (a.findtext("LastName") or "").strip()
            ini = (a.findtext("Initials") or "").strip()
            if ln:
                authors.append(f"{ln} {ini}".strip())
            elif (a.findtext("CollectiveName") or "").strip():
                authors.append(a.findtext("CollectiveName").strip())
        pubtypes = [(pt.text or "").strip()
                    for pt in cit.findall(".//PublicationTypeList/PublicationType")]
        items.append({
            "pmid": pmid, "title": title, "journal": journal,
            "date": epub or pubdate, "doi": doi, "authors": authors,
            "abstract": abstract, "pubtypes": pubtypes, "source": "pubmed",
        })
    return items


def fetch_pubmed(start: datetime, end: datetime) -> tuple[list[dict], list[str]]:
    """Four E-utilities searches -> parsed, deduped items. Returns (items, errors)."""
    errors: list[str] = []
    by_pmid: dict[str, dict] = {}
    for q in _queries():
        try:
            params = urllib.parse.urlencode({
                "db": "pubmed", "term": q["term"], "retmode": "json",
                "retmax": q["max"], "datetype": "edat",
                "reldate": WINDOW_DAYS, "sort": "pub_date"})
            d = json.loads(http_get(f"{EUTILS}esearch.fcgi?{params}").decode())
            res = d.get("esearchresult", {})
            ids = [i for i in res.get("idlist", []) if i]
            log(f"  {q['name']}: {res.get('count')} hit(s), "
                f"{len(ids)} fetched (max {q['max']})")
            if not ids:
                continue
            xml = http_post(
                f"{EUTILS}efetch.fcgi",
                urllib.parse.urlencode({
                    "db": "pubmed", "id": ",".join(ids),
                    "retmode": "xml", "rettype": "abstract"}).encode(),
                "application/x-www-form-urlencoded", timeout=90)
            for it in parse_pubmed_xml(xml):
                it["kind"] = classify_kind(it)
                it["query"] = q["name"]
                if it["pmid"] not in by_pmid:
                    by_pmid[it["pmid"]] = it
            time.sleep(0.4)  # be polite to E-utilities
        except Exception as e:  # noqa: BLE001
            msg = f"pubmed {q['name']}: {type(e).__name__}: {e}"
            log(f"  ERROR {msg}")
            errors.append(msg)
    return list(by_pmid.values()), errors


def classify_kind(it: dict) -> str:
    pts = " ".join(it.get("pubtypes") or []).lower()
    t = (it.get("title") or "").lower()
    if "guideline" in pts or "consensus development conference" in pts:
        return "guideline"
    if re.search(r"\b(guideline|guidance|position statement|delphi|"
                 r"clinical practice update|standards of practice)\b", t):
        return "guideline"
    if "consensus" in t or re.search(r"\bexpert (consensus|review)\b", t):
        return "consensus"
    if "meta-analysis" in pts or "meta-analysis" in t:
        return "meta-analysis"
    if "systematic review" in pts or "systematic review" in t:
        return "systematic review"
    if "randomized controlled trial" in pts or "controlled clinical trial" in pts \
            or "clinical trial, phase" in pts:
        return "trial"
    if re.search(r"\b(randomi[sz]ed|randomi[sz]ed controlled|phase (1|2|3|ii|iii))\b", t):
        return "trial"
    return "study"


# ── Fetch: Europe PMC (tier 2) ───────────────────────────────────────────────
def fetch_epmc(start: datetime, end: datetime) -> tuple[list[dict], list[str]]:
    s, e = start.strftime("%Y-%m-%d"), end.strftime("%Y-%m-%d")
    jour = " OR ".join(f'JOURNAL:"{j}"' for j in GI_JOURNALS)
    guid = ('(PUB_TYPE:"Practice Guideline" OR PUB_TYPE:"Guideline" OR '
            'TITLE:"consensus" OR TITLE:"guideline" OR TITLE:"guidelines" OR '
            'TITLE:"recommendations" OR TITLE:"position statement")')
    trials = ('(PUB_TYPE:"Randomized Controlled Trial" OR '
              'PUB_TYPE:"Meta-Analysis" OR PUB_TYPE:"Systematic Review" OR '
              'PUB_TYPE:"Clinical Trial" OR PUB_TYPE:"Review")')
    mesh = ' OR '.join(f'MESH:"{m}"' for m in GI_MESH)
    queries = [
        ("guide_journal", f"{guid} AND ({jour})"),
        ("guide_topic", f"{guid} AND ({mesh})"),
        ("trial_journal", f"{trials} AND ({jour})"),
    ]
    errors: list[str] = []
    by_pmid: dict[str, dict] = {}
    cap = {"guide_journal": MAX_GUIDE_CANDIDATES,
           "guide_topic": MAX_GUIDE_CANDIDATES,
           "trial_journal": MAX_TRIAL_CANDIDATES}
    for name, q in queries:
        try:
            params = urllib.parse.urlencode({
                "query": f'({q}) AND FIRST_PDATE:[{s} TO {e}] AND SRC:MED',
                "format": "json", "resultType": "core",
                "pageSize": cap[name]})
            d = json.loads(http_get(f"{EPMC}?{params}", timeout=60).decode())
            rows = d.get("resultList", {}).get("result", [])
            log(f"  epmc {name}: {d.get('hitCount')} hit(s), {len(rows)} fetched")
            for r in rows:
                pmid = str(r.get("pmid") or r.get("id") or "").strip()
                if not pmid:
                    continue
                ji = (r.get("journalInfo") or {})
                jrec = (ji.get("journal") or {})
                journal = (jrec.get("title") or jrec.get("medlineAbbreviation")
                           or "").strip()
                pts = (r.get("pubTypeList") or {}).get("pubType") or []
                it = {
                    "pmid": pmid,
                    "title": re.sub(r"\s+", " ", r.get("title") or "").strip(),
                    "journal": journal,
                    "date": str(r.get("firstPublicationDate")
                                or r.get("firstIndexDate") or "")[:10],
                    "doi": r.get("doi") or "",
                    "authors": [],
                    "abstract": re.sub(r"\s+", " ",
                                       r.get("abstractText") or "").strip(),
                    "pubtypes": [str(p) for p in pts],
                    "source": "europepmc", "query": name,
                }
                it["kind"] = classify_kind(it)
                if it["pmid"] not in by_pmid:
                    by_pmid[it["pmid"]] = it
            time.sleep(0.3)
        except Exception as e:  # noqa: BLE001
            msg = f"epmc {name}: {type(e).__name__}: {e}"
            log(f"  ERROR {msg}")
            errors.append(msg)
    return list(by_pmid.values()), errors


