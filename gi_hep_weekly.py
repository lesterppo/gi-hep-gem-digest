# ── HTTP ─────────────────────────────────────────────────────────────────────
def _retry_after(msg: str) -> float | None:
    m = re.search(r"retry-after[:\s]+(\d+)", msg, re.I)
    return float(m.group(1)) if m else None


def http_get(url: str, timeout: int = 45, tries: int = HTTP_TRIES) -> bytes:
    """GET with a retry ladder (429/5xx/transient), honouring Retry-After."""
    last = ""
    for attempt in range(1, tries + 1):
        try:
            req = urllib.request.Request(url, headers={
                "User-Agent": UA, "Accept": "*/*"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            body = ""
            try:
                body = e.read().decode("utf-8", "replace")[:200]
            except Exception:
                pass
            last = f"HTTP {e.code}: {body or e.reason}"
            retryable = e.code == 429 or 500 <= e.code < 600
            if not retryable or attempt == tries:
                break
            wait = _retry_after(f"{e.headers.get('Retry-After', '')} ") \
                or 3.0 * attempt
            log(f"  http {e.code} — retry in {wait:.0f}s ({url[:90]})")
            time.sleep(min(wait, 45))
        except Exception as e:  # noqa: BLE001 — transient socket/timeouts
            last = f"{type(e).__name__}: {e}"
            if attempt == tries:
                break
            wait = 2.0 * attempt
            log(f"  http transient ({last[:80]}) — retry in {wait:.0f}s")
            time.sleep(wait)
    raise RuntimeError(f"GET failed after {tries} tries: {url[:110]} — {last}")


def http_post(url: str, data: bytes, content_type: str,
              timeout: int = 45, tries: int = HTTP_TRIES) -> bytes:
    last = ""
    for attempt in range(1, tries + 1):
        try:
            req = urllib.request.Request(url, data=data, headers={
                "User-Agent": UA, "Content-Type": content_type,
                "Accept": "*/*"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            body = ""
            try:
                body = e.read().decode("utf-8", "replace")[:200]
            except Exception:
                pass
            last = f"HTTP {e.code}: {body or e.reason}"
            if not (e.code == 429 or 500 <= e.code < 600) or attempt == tries:
                break
            time.sleep(min(_retry_after(
                f"{e.headers.get('Retry-After','')} ") or 3.0 * attempt, 45))
        except Exception as e:  # noqa: BLE001
            last = f"{type(e).__name__}: {e}"
            if attempt == tries:
                break
            time.sleep(2.0 * attempt)
    raise RuntimeError(f"POST failed after {tries} tries: {url[:110]} — {last}")


