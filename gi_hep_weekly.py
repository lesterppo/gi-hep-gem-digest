# p-value handling: drop standalone "(p = 0.03)" groups first, then loose
# "..., p = 0.03" tokens, so the surrounding sentence keeps its brackets.
PVAL_GROUP_RE = re.compile(r"\(\s*p\s*[=<>]\s*0?\.\d+\s*\)", re.I)
PVAL_RE = re.compile(r"\s*[,;]?\s*\bp\s*[=<>]\s*0?\.\d+\b", re.I)


LATEX_MAP = {"\\ge": ">=", "\\le": "<=", "\\pm": "+/-", "\\times": "x",
             "\\%": "%", "\\&": chr(38), "\\sim": "~", "\\approx": "~"}


def _strip_stats(s: str) -> str:
    """Remove p-values and Gemini LaTeX leftovers.

    The digest prompt excludes p-values, and any that leak through get garbled
    by the artifact generator and paired with contradictory 'significant'
    claims; raw LaTeX ($\\ge$5.0) also renders as noise in the infographic."""
    s = s or ""
    for k, v in LATEX_MAP.items():
        s = s.replace(k, v)
    s = re.sub(r"\$+([^$]*)\$+", r"\1", s)
    s = PVAL_GROUP_RE.sub("", s)
    s = PVAL_RE.sub("", s)
    s = re.sub(r"\(\s*[,;]?\s*\)", "", s)      # empty parentheses
    s = re.sub(r"\(\s*[,;]\s*", "(", s)        # dangling separator
    s = re.sub(r"[,;]\s*\)", ")", s)            # dangling separator
    s = re.sub(r"\s*[,;]\s*([.;])", r"\1", s)
    s = re.sub(r"\b(and|or)\s*[,;]", ",", s)      # 'and p<0.001;' -> ','
    s = re.sub(r"\s+([,;%.])", r"\1", s)
    s = re.sub(r"\s{2,}", " ", s)
    return s.strip(" ,;.")


def parse_digest_notes(digest_text: str) -> dict:
    """digest markdown -> {pmid: {title, type, citation, what, impact, caveat}}.

    NotebookLM garbles numbers when it is fed raw abstracts, so the notebook
    sources carry these curated lines instead."""
    out: dict = {}
    for b in re.split(r"\n(?=###\s)", digest_text or ""):
        m = re.search(r"PMID\s+(\d{6,9})", b)
        if not m:
            continue
        title_m = re.match(r"###\s+(.*)", b.strip())

        def field(name: str, blk: str = b) -> str:
            fm = re.search(rf"\*\*{name}\*\*:\s*(.*)", blk)
            return _strip_stats(fm.group(1).strip()) if fm else ""

        out[m.group(1)] = {
            "title": (title_m.group(1).strip() if title_m else ""),
            "type": field("Type"),
            "citation": field("Citation"),
            "what": field("What it says"),
            "impact": field("Practice impact"),
            "caveat": field("Caveat"),
        }
    return out


NUM_RE = re.compile(r"\d|\bCI\b|\bHR\b|\bOR\b|\bRR\b|\bNNT\b|\bvs\b|%")


def _key_points(text: str, kind: str, n: int = 2, cap: int = 340) -> str:
    """Two sentences of substance; for studies prefer sentences carrying the
    headline numbers, otherwise the trial cards come out result-less."""
    parts = [p for p in re.split(r"(?<=[.;])\s+", (text or "").strip()) if p]
    if kind in ("trial", "meta-analysis", "systematic review"):
        numbered = [p for p in parts if NUM_RE.search(p)]
        parts = (numbered[:n] + [p for p in parts if p not in numbered])[:n] \
            if numbered else parts[:n]
    return " ".join(parts[:n])[:cap].strip()


def gihep_notebook_sources(items: list, digest_text: str,
                           cap: int | None = None) -> list:
    """Compact, curated per-item source blocks (guidance before studies)."""
    notes = parse_digest_notes(digest_text)
    ordered = sorted(items, key=lambda x: KIND_ORDER.get(x["kind"], 9))
    # Balanced selection so the notebook feeds BOTH infographic sections:
    # without this the guidance-heavy window starves the trials section and the
    # artifact drops it entirely.
    cap = cap or NLM_MAX_SOURCES
    if len(ordered) <= cap:
        picked = ordered          # a thematic dashboard keeps all its items
    else:
        guide = [it for it in ordered
                 if it["kind"] in ("guideline", "consensus")][:NLM_GUIDE_SOURCES]
        study = [it for it in ordered
                 if it["kind"] in ("trial", "meta-analysis", "systematic review")
                 ][:NLM_STUDY_SOURCES]
        picked = (guide + study)[:cap] or ordered[:cap]
    out = []
    for it in picked:
        n = notes.get(it["pmid"], {})
        soc = SOCIETY_RE.search(it.get("title", "") + " " +
                                (it.get("abstract") or "")[:300])
        lines = [
            f"TYPE: {n.get('type') or it['kind']}",
            f"SOCIETY: {soc.group(1) if soc else 'not stated'}",
            f"JOURNAL: {it.get('journal', '?')}",
            f"DATE: {it.get('date', '')}",
            f"PMID: {it['pmid']}",
            f"TITLE: {n.get('title') or it.get('title', '')}",
        ]
        if n.get("what"):
            kp = _key_points(n["what"], it["kind"])
            label = ("RESULT" if it["kind"] in ("trial", "meta-analysis",
                                               "systematic review")
                     else "KEY POINTS")
            lines.append(f"{label}: {kp}")
        if n.get("impact"):
            lines.append("PRACTICE: " + n["impact"][:220])
        if n.get("caveat"):
            lines.append("CAVEAT: " + n["caveat"][:180])
        if not n.get("what"):
            lines.append("ABSTRACT: " + _strip_stats(
                (it.get("abstract") or "")[:700]))
        out.append({"title": f"PMID {it['pmid']} — {it['kind']} — "
                             f"{(it.get('journal') or '')[:28]}",
                    "text": "\n".join(lines)})
    return out


LIVER_RE = re.compile(
    r"\b(hepat|liver|cirrhos|hcc|hepatocellular|biliary|cholest|mash|masld|"
    r"nafld|hbv|hcv|portal|varice|ascites|fibroscan|endoscop\w* varice)\b",
    re.I)


def plan_dashboards(items: list, max_c = None) -> list:
    """Split the window into thematic dashboards.

    One big artifact for the whole window forces the generator to cram, which
    is exactly where garble and dropped sections come from. Narrow dashboards
    let each one summarise deeply instead."""
    guide = [it for it in items if it["kind"] in ("guideline", "consensus")]
    study = [it for it in items
             if it["kind"] in ("trial", "meta-analysis", "systematic review")]
    plans = [
        {"key": "guidance", "notebook": "Guidance & Consensus",
         "caption": "New guidance & consensus — every recommendation in this "
                    "window's guidelines and expert statements (Gemini "
                    "NotebookLM)",
         "items": guide[:10]},
        {"key": "trials", "notebook": "Trials & Meta-analyses",
         "caption": "Pivotal trials & meta-analyses — populations, comparators "
                    "and the headline numbers (Gemini NotebookLM)",
         "items": study[:8]},
        {"key": "signals", "notebook": "Practice Signals",
         "caption": "Practice signals across the week — what to change, what to "
                    "verify, what to watch (Gemini NotebookLM)",
         "items": (guide[:5] + study[:4]
                   + [it for it in items if it not in guide + study][:3]),
         "cap": 12},
    ]
    return [pl for pl in plans if pl["items"]]


