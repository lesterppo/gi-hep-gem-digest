def render_email(date_label: str, digest_text: str, items: list[dict],
                 also_indexed: list[dict], cids: list[str],
                 meta_note: str) -> str:
    labels = ["Evidence mix this week (rendered from the digest data: type, "
              "journal and issuing-body counts)",
              "Comprehensive clinical infographic generated by Gemini "
              "NotebookLM from the attached item sources"]
    info = ""
    if cids:
        info = "<h4>At a glance</h4>"
        for i, cid in enumerate(cids):
            info += (f"<img class='infographic' src='cid:{cid}' "
                     f"alt='digest infographic {i+1}'/>")
            if i < len(labels):
                info += f"<div class='cap'>{labels[i]}</div>"
        info += "<hr/>"
    src_rows = "".join(
        f"<tr><td>{it['kind']}</td><td>{(it.get('journal') or '?')}</td>"
        f"<td>{it.get('date','')}</td>"
        f"<td><a href='https://pubmed.ncbi.nlm.nih.gov/{it['pmid']}/'>"
        f"PMID {it['pmid']}</a></td>"
        f"<td>{_html.escape((it.get('title') or '')[:110])}</td></tr>"
        for it in items)
    also = ""
    if also_indexed:
        rows = "".join(
            f"<li><a href='https://pubmed.ncbi.nlm.nih.gov/{it['pmid']}/'>"
            f"PMID {it['pmid']}</a> — {_html.escape((it.get('journal') or '?'))} "
            f"{it.get('date','')} — {_html.escape((it.get('title') or '')[:110])}"
            f" <span class='meta'>[{it['kind']}]</span></li>"
            for it in also_indexed[:BREAKING_LIMIT])
        also = (f"<h4>Also indexed this week (not analysed)</h4>"
                f"<ul class='also'>{rows}</ul>")
    return (f"<html><head><meta charset='utf-8'>{CSS}</head><body>"
            f"<h1>GI &amp; Hepatology Weekly</h1>"
            f"<div class='meta'>Guidelines, consensus statements and clinical "
            f"studies newly indexed in PubMed. Generated {date_label} by "
            f"Gemini Flash + Extended Thinking"
            + (f" ({_html.escape(meta_note)})" if meta_note else "")
            + f". Window: last {WINDOW_DAYS} days. "
            f"{len(items)} item(s) analysed.</div>"
            f"<div class='banner'>Ranking-free digest: every new guideline, "
            f"consensus statement, randomised trial and meta-analysis in "
            f"gastroenterology &amp; hepatology for this window is summarised "
            f"with its numbers and its practice implication.</div>"
            f"<hr/>{info}"
            f"{md_to_htmlish(digest_text)}"
            f"<hr/><h4>Items analysed this week</h4>"
            f"<table><tr><th>Type</th><th>Journal</th><th>Date</th>"
            f"<th>PMID</th><th>Title</th></tr>{src_rows}</table>"
            f"{also}"
            f"<hr/><div class='meta'>Sources: PubMed E-utilities "
            f"(guideline/consensus publication types, GI-hepatology journals, "
            f"GI-hepatology MeSH topics), Europe PMC as fallback. "
            f"Automated summary — verify full texts before changing practice."
            f"</div></body></html>")


def render_warn_email(date_label: str, detail: str) -> str:
    return (f"<html><head><meta charset='utf-8'>{CSS}</head><body>"
            f"<h1>GI &amp; Hepatology Weekly — no digest produced</h1>"
            f"<div class='banner'>The fetcher returned no items <b>and</b> at "
            f"least one source errored, so this is a WARN run rather than a "
            f"silently empty digest. {date_label}</div>"
            f"<h4>Errors</h4><pre>{_html.escape(detail[:3000])}</pre>"
            f"<div class='meta'>Re-run the workflow manually once the upstream "
            f"source is reachable (workflow_dispatch).</div></body></html>")


# ── Main ─────────────────────────────────────────────────────────────────────
def main() -> int:
    t_start = time.time()
    now = datetime.now(timezone.utc)
    end = now
    start = end - timedelta(days=WINDOW_DAYS)
    date_label = datetime.now().strftime("%Y-%m-%d")
    log(f"=== GI & Hepatology weekly digest starting "
        f"(window {WINDOW_DAYS}d, model {GEMINI_MODEL}+{GEMINI_THINKING}) ===")
    setup_auth_from_env()

    errors: list[str] = []
    items: list[dict] = []
    order = [FETCH_SOURCE] if FETCH_SOURCE in ("pubmed", "epmc") \
        else ["pubmed", "epmc"]
    for tier in order:
        try:
            log(f"Fetching via {tier} …")
            got, errs = (fetch_pubmed(start, end) if tier == "pubmed"
                         else fetch_epmc(start, end))
            errors += errs
            items += got
            log(f"  {tier}: {len(got)} item(s) ({len(errs)} error(s))")
        except Exception as e:  # noqa: BLE001
            msg = f"{tier} fetch crashed: {type(e).__name__}: {e}"
            log(f"  ERROR {msg}")
            errors.append(msg)
        if items and FETCH_SOURCE == "auto":
            break
    # If the primary tier returned a thin set, still try the fallback tier
    if items and FETCH_SOURCE == "auto" and len(items) < 5:
        try:
            log("Thin primary result — also querying europepmc …")
            got, errs = fetch_epmc(start, end)
            errors += errs
            known = {i["pmid"] for i in items}
            fresh = [g for g in got if g["pmid"] not in known]
            items += fresh
            log(f"  europepmc added {len(fresh)} item(s)")
        except Exception as e:  # noqa: BLE001
            log(f"  ERROR epmc supplement: {e}")

    seen = _load_seen()
    log(f"Seen-cache: {len(seen)} known PMID(s)")
    todo, dupes, dropped = select_items(items, seen)
    log(f"Fetched {len(items)} unique item(s); {len(dupes)} already reported; "
        f"{len(todo)} to analyse; {len(dropped)} over capacity")

    if not items:
        detail = "\n".join(errors) or "no errors reported — genuinely empty window"
        subj = f"GI & Hepatology Weekly — WARN (no items) {date_label}"
        body = render_warn_email(date_label, detail)
        send_email(subj, body)
        if errors:
            log("WARN run: no items and source errors — exit 2")
            return 2
        log("No items in window, no errors — exit 0")
        return 0

    if not todo:
        log("Nothing new since the last run — informational email only")
        body = render_email(
            date_label,
            "## Week in focus\n- No new guidelines, consensus statements or "
            "clinical studies were newly indexed for this window "
            "(everything fetched was already reported in a previous run).",
            [], [], [], "no new items")
        send_email(f"GI & Hepatology Weekly — no new items {date_label}", body)
        return 0

    analysis = analyze(todo)
    if not analysis["ok"]:
        detail = "\n".join(errors + analysis["errors"])
        log(f"Gemini analysis failed on every batch — WARN email. "
            f"{detail[:300]}")
        send_email(f"GI & Hepatology Weekly — WARN (analysis failed) {date_label}",
                   render_warn_email(date_label, detail))
        return 2

    meta_note = ", ".join(sorted({b for b in analysis["backends"] if b}))
    chart = nlm_img = ""
    try:
        chart = render_evidence_chart(todo, OUT_DIR)
        log(f"matplotlib chart: {chart}")
    except Exception as e:  # noqa: BLE001
        log(f"ERROR chart render: {type(e).__name__}: {e}")
    date_range = f"{start:%Y-%m-%d} to {end:%Y-%m-%d}"
    nlm_img = make_notebooklm_infographic(todo, analysis["text"],
                                          date_label, date_range)
    if not nlm_img:
        meta_note = (meta_note + "; NotebookLM infographic unavailable this "
                     "run — text summary + evidence-mix chart only")

    imgs = [p for p in (chart, nlm_img) if p]
    cids = [f"infographic{i}" for i in range(len(imgs))]
    body = render_email(date_label, analysis["text"], todo, dropped, cids,
                        meta_note)
    subj = (f"GI & Hepatology Weekly — {len(todo)} item(s) "
            f"(guidelines, consensus & trials) {date_label}")
    status = send_email(subj, body, imgs, cids)

    if status == "sent":
        for it in todo:
            seen[it["pmid"]] = date_label
        seen = _prune_seen(seen)
        _save_seen(seen)
        log(f"Seen-cache updated: {len(seen)} entries")

    log(f"=== done in {time.time()-t_start:.0f}s — {len(todo)} analysed, "
        f"{len(imgs)} infographic(s), backend {meta_note}, email {status} ===")
    if analysis["errors"]:
        log(f"(partial batch failures: {analysis['errors']})")
        return 0 if len(analysis["errors"]) < max(1, len(todo) // BATCH_SIZE + 1) else 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
