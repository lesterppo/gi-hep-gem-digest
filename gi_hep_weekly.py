def md_to_htmlish(text: str) -> str:
    """Markdown -> email-safe HTML. Escapes HTML first. Linkifies PMIDs and
    journal citations of the form 'PMID 12345678'."""
    esc = (text.replace("&", "&amp;").replace("<", "&lt;")
           .replace(">", "&gt;"))

    def _inline(s: str) -> str:
        s = re.sub(r"\[([^\]]+)\]\((https?://[^)]+)\)",
                   r'<a href="\2">\1</a>', s)
        s = re.sub(r"(?<![/\d])PMID[:\s]*(\d{6,9})(?![\d/])",
                   r'PMID <a href="https://pubmed.ncbi.nlm.nih.gov/\1/">\1</a>',
                   s)
        s = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", s)
        s = re.sub(r"(?<!\*)\*([^*\s][^*]*)\*(?!\*)", r"<i>\1</i>", s)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        return s

    lines = []
    in_ul = False
    for raw in esc.splitlines():
        stripped = raw.rstrip().strip()
        if not stripped:
            if in_ul:
                lines.append("</ul>")
                in_ul = False
            lines.append("<br/>")
            continue
        m = re.match(r"^(#{1,4})\s+(.*)", stripped)
        if m:
            if in_ul:
                lines.append("</ul>")
                in_ul = False
            tag = "h3" if len(m.group(1)) <= 2 else "h4"
            lines.append(f"<{tag}>{_inline(m.group(2))}</{tag}>")
            continue
        m = re.match(r"^[-*]\s+(.*)", stripped)
        if m:
            if not in_ul:
                lines.append("<ul>")
                in_ul = True
            lines.append(f"<li>{_inline(m.group(1))}</li>")
            continue
        if in_ul:
            lines.append("</ul>")
            in_ul = False
        lines.append(_inline(stripped))
    if in_ul:
        lines.append("</ul>")
    return "<br/>".join(lines)


