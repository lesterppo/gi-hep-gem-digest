def _gemini_web(prompt: str, batch_label: str) -> dict:
    """Gemini Flash + Extended Thinking through gemini.py (cookie auth)."""
    out_path = os.path.join(SCRIPT_DIR, "state", f"digest_{batch_label}.md")
    args = [sys.executable, GEMINI_SCRIPT, "-m", GEMINI_MODEL,
            "--thinking", GEMINI_THINKING, "--raw", "--brief",
            "-o", out_path, "-p", prompt]
    env = dict(os.environ, PYTHONUNBUFFERED="1")
    last = ""
    for attempt in range(1, GEMINI_RETRIES + 2):
        try:
            proc = subprocess.run(args, capture_output=True, text=True,
                                  env=env, timeout=GEMINI_TIMEOUT)
            out = (proc.stdout or "").strip()
            try:
                parsed = json.loads(out) if out else {}
            except json.JSONDecodeError:
                parsed = {}
            if parsed.get("ok"):
                f = parsed.get("f")
                if f and os.path.exists(f):
                    with open(f, encoding="utf-8") as fh:
                        return {"ok": True, "text": fh.read(), "backend": "web"}
                return {"ok": True, "text": parsed.get("text", ""),
                        "backend": "web"}
            last = (parsed.get("err") or proc.stderr.strip() or out[:300]
                    or "unknown")
            if attempt <= GEMINI_RETRIES:
                log(f"  gemini(web) attempt {attempt} err {last[:120]} — retry")
                time.sleep(8 * attempt)
        except subprocess.TimeoutExpired:
            last = "TIMEOUT"
            if attempt <= GEMINI_RETRIES:
                log(f"  gemini(web) attempt {attempt} timeout — retry")
                time.sleep(8 * attempt)
    return {"ok": False, "err": last, "backend": "web"}


def _gemini_api(prompt: str) -> dict:
    """Fallback backend: free-tier AI Studio API key (no browser, no cookies)."""
    if not GEMINI_API_KEY:
        return {"ok": False, "err": "NO_API_KEY", "backend": "api"}
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "maxOutputTokens": 65536,
            "thinkingConfig": {"thinkingBudget": 16384,
                               "includeThoughts": False},
        },
    }
    last = ""
    for model in GEMINI_API_MODELS:
        for attempt in (1, 2):
            try:
                req = urllib.request.Request(
                    "https://generativelanguage.googleapis.com/v1beta/models/"
                    f"{model}:generateContent",
                    data=json.dumps(body).encode(),
                    headers={"Content-Type": "application/json",
                             "x-goog-api-key": GEMINI_API_KEY})
                with urllib.request.urlopen(req, timeout=GEMINI_TIMEOUT) as r:
                    d = json.load(r)
                cands = d.get("candidates") or []
                if not cands:
                    last = f"{model}: no candidates ({str(d)[:160]})"
                    continue
                text = "".join(p.get("text", "")
                               for p in cands[0].get("content", {})
                               .get("parts", []))
                if not text.strip():
                    last = (f"{model}: empty text "
                            f"(finishReason={cands[0].get('finishReason')})")
                    continue
                log(f"  gemini(api) ok via {model}")
                return {"ok": True, "text": text, "backend": f"api:{model}"}
            except urllib.error.HTTPError as e:
                detail = ""
                try:
                    detail = e.read().decode("utf-8", "replace")[:200]
                except Exception:
                    pass
                last = f"{model} HTTP {e.code}: {detail}"
                if e.code in (429, 500, 503) and attempt == 1:
                    time.sleep(6)
                    continue
                break
            except Exception as e:  # noqa: BLE001
                last = f"{model} {type(e).__name__}: {e}"
                if attempt == 1:
                    time.sleep(4)
                    continue
                break
    return {"ok": False, "err": last or "unknown", "backend": "api"}


def gemini_analyze(prompt: str, batch_label: str) -> dict:
    """Web (Flash + Extended) first; fall back to the API-key backend."""
    if FETCH_SOURCE not in ("api_only",):
        res = _gemini_web(prompt, batch_label)
        if res.get("ok"):
            return res
        log(f"  gemini(web) failed: {str(res.get('err'))[:140]} — "
            f"falling back to API key backend")
    else:
        res = {"ok": False, "err": "skipped-by-config"}
    api = _gemini_api(prompt)
    if api.get("ok"):
        return api
    return {"ok": False, "err": f"web={res.get('err')} api={api.get('err')}"}


